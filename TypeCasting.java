

public class TypeCasting{
public static void main(String args[]){
   //Implicit and Explicit typecasting 
   int a = 10;
   double b = a;//implicite typecasting
   System.out.println(b);
  
   //explicit and Explicit typecasting 
    double c = 10;
    int d = (int)c;
    System.out.println(d);

   
   

   
}
}